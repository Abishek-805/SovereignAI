const { chromium } = require('playwright');
(async () => {
 const browser=await chromium.launch({headless:true, executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 try {
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  page.setDefaultTimeout(20000);
  const identity=await page.request.get('http://127.0.0.1:8088/status');
  if(identity.headers()['x-sovereign-audit']!=='disposable') throw Error('Refusing to test against a non-disposable backend');
  await page.goto('http://127.0.0.1:8088');
  await page.getByRole('navigation',{name:'Primary workbench navigation'}).getByRole('button',{name:'Knowledge',exact:true}).click();
  const library=page.getByRole('region',{name:'Knowledge library'});
  await library.waitFor();
  await library.locator('input[type=file]').first().setInputFiles({name:'browser-notes.tsv',mimeType:'text/tab-separated-values',buffer:Buffer.from('Name\tValue\nEarth\t42')});
  await library.getByRole('button',{name:'Stop import',exact:true}).waitFor();
  await library.getByText('1 document indexed.',{exact:true}).waitFor();
  if(!(await page.request.get('http://127.0.0.1:8088/documents')).ok()) throw Error('Library request failed');
  await library.locator('input[type=file]').first().setInputFiles({name:'cancel-browser.txt',mimeType:'text/plain',buffer:Buffer.from('Another passage about Earth.\n'.repeat(800))});
  await library.getByRole('button',{name:'Stop import',exact:true}).click();
  await library.getByText(/stopped before/).waitFor();
  const documents=await (await page.request.get('http://127.0.0.1:8088/documents')).json();
  if(!documents.some(d=>d.display_name==='cancel-browser.txt'&&d.indexing_status==='failed'&&d.chunk_count===0)) throw Error('Cancelled upload should retain its original but no published index');
  await library.locator('input[type=file]').first().setInputFiles({name:'browser-large.tsv',mimeType:'text/tab-separated-values',buffer:Buffer.from('name\tvalue\n'+Array.from({length:120},(_,i)=>`Record-${i}\t${i}`).join('\n'))});
  await library.getByText('1 document indexed.',{exact:true}).waitFor();
  await library.getByRole('button',{name:/browser-large.tsv/}).click();
  await library.getByRole('button',{name:'Extracted text',exact:true}).click();
  const pagination=library.getByRole('navigation',{name:'Document passages'});
  await pagination.getByRole('button',{name:'Next passages'}).click();
  await pagination.getByText('Passages 101–121 of 121',{exact:true}).waitFor();
  if(await library.locator('[id^="passage-"]').count()!==21) throw Error('Large preview did not paginate');
  await pagination.getByRole('button',{name:'Previous passages'}).click();
  await pagination.getByText('Passages 1–100 of 121',{exact:true}).waitFor();
  const workbook=await (await page.request.get('http://127.0.0.1:8088/__audit_workbook__')).body();
  await library.locator('input[type=file]').first().setInputFiles({name:'original-grid.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:workbook});
  await library.getByRole('table',{name:'Results',exact:true}).waitFor();
  await library.getByRole('cell',{name:'Learner 0',exact:true}).waitFor();
  await library.getByRole('button',{name:'Notes',exact:true}).click();
  await library.getByRole('cell',{name:'Original note',exact:true}).waitFor();
  const find=library.getByRole('searchbox',{name:'Find cell values'});
  await find.fill('Learner 149');
  await find.press('Enter');
  await library.getByRole('table',{name:'Results',exact:true}).waitFor();
  await library.getByRole('cell',{name:'Learner 149',exact:true}).waitFor();
  await find.fill('original note');
  await find.press('Enter');
  await library.getByRole('cell',{name:'Original note',exact:true}).waitFor();
  await library.getByRole('checkbox',{name:'Match case',exact:true}).check();
  await find.press('Enter');
  await library.getByText('No matches',{exact:true}).waitFor();
  await library.getByRole('checkbox',{name:'Match case',exact:true}).uncheck();
  await library.getByText('1 document indexed.',{exact:true}).waitFor();
  const workspace=await (await page.request.post('http://127.0.0.1:8088/coding/workspaces',{data:{name:'Disposable deletion review'}})).json();
  await page.request.put(`http://127.0.0.1:8088/coding/workspaces/${workspace.workspace_id}/files/notes.txt`,{data:{content:'Retain until accepted',expected_sha256:''}});
  await page.evaluate(id=>localStorage.setItem('sovereign-active-workspace',id),workspace.workspace_id);
  await page.getByRole('navigation',{name:'Primary workbench navigation'}).getByRole('button',{name:'Code',exact:true}).click();
  await page.getByRole('textbox',{name:'Coding task',exact:true}).fill('Delete all files in this workspace');
  await page.getByRole('textbox',{name:'Coding task',exact:true}).press('Enter');
  const removals=page.getByRole('list',{name:'Pending project changes'});
  await removals.getByText('notes.txt',{exact:false}).waitFor();
  await page.getByText('Will remove',{exact:true}).waitFor();
  const before=await (await page.request.get(`http://127.0.0.1:8088/coding/workspaces/${workspace.workspace_id}`)).json();
  if(before.files.length!==1)throw Error('A staged deletion modified canonical files before acceptance');
  await page.locator('.review-actions').getByRole('button',{name:'Accept changes',exact:true}).click();
  await page.getByText('Changes accepted and saved to the project.',{exact:true}).waitFor();
  const after=await (await page.request.get(`http://127.0.0.1:8088/coding/workspaces/${workspace.workspace_id}`)).json();
  if(after.files.length!==0)throw Error('Accepted deletion did not remove canonical file');
  await page.getByRole('button',{name:'Manage workspaces',exact:true}).click();
  const manager=page.getByRole('dialog',{name:'Manage workspaces',exact:true});
  await manager.getByRole('checkbox',{name:'Select all available workspaces'}).check();
  await manager.getByRole('button',{name:/^Delete selected \(/}).click();
  await manager.getByText('Disposable deletion review',{exact:true}).waitFor();
  await manager.getByRole('button',{name:/^Delete \d+ workspaces?$/}).click();
  await manager.getByRole('button',{name:'Close',exact:true}).click();
  const deleted=await page.request.get(`http://127.0.0.1:8088/coding/workspaces/${workspace.workspace_id}`);
  if(deleted.ok())throw Error('Selected workspace was not deleted');
  await page.request.post('http://127.0.0.1:8088/__audit_shutdown__');
  console.log('Browser import, worksheet Find, cancellation, pagination, Code acceptance and workspace selection/deletion passed on disposable data.');
 } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
