const { chromium } = require('playwright');

(async () => {
 const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
 const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark', serviceWorkers: 'block' });
 page.setDefaultTimeout(25000);
 const errors = [];
 page.on('pageerror', error => errors.push(String(error)));
 try {
  await page.goto('http://127.0.0.1:8088/#/');
  const nav = page.getByRole('navigation', { name: 'Primary workbench navigation' });
  await nav.getByRole('button', { name: 'Code' }).click();
  const ide = page.getByRole('region', { name: 'Coding workspace' });
  const explorer = ide.locator('.explorer');
  const assistant = ide.locator('.ai-panel');
  const beforeExplorer = await explorer.boundingBox();
  const leftHandle = ide.getByRole('button', { name: 'Resize Explorer panel' });
  const handleBox = await leftHandle.boundingBox();
  if (!handleBox) throw Error('Explorer resize handle missing');
  await page.mouse.move(handleBox.x + 5, handleBox.y + 180);
  await page.mouse.down();
  await page.mouse.move(handleBox.x + 65, handleBox.y + 180, { steps: 6 });
  await page.mouse.up();
  const afterExplorer = await explorer.boundingBox();
  if (!beforeExplorer || !afterExplorer || afterExplorer.width <= beforeExplorer.width + 25) throw Error('Explorer drag resize failed');
  const beforeAssistant = await assistant.boundingBox();
  const rightHandle = ide.getByRole('button', { name: 'Resize Assistant panel' });
  await rightHandle.focus();
  await page.keyboard.press('ArrowLeft');
  const afterAssistant = await assistant.boundingBox();
  if (!beforeAssistant || !afterAssistant || afterAssistant.width <= beforeAssistant.width) throw Error('Assistant keyboard resize failed');
  await ide.getByRole('button', { name: 'Shortcuts' }).click();
  await ide.getByRole('dialog', { name: 'Windows keyboard shortcuts' }).waitFor();
  await page.keyboard.press('Escape');
  if (await ide.getByRole('dialog', { name: 'Windows keyboard shortcuts' }).count()) throw Error('Shortcut dialog did not close');
  await nav.getByRole('button', { name: 'Control Center' }).click();
  await page.getByRole('navigation', { name: 'Control Center sections' }).getByRole('button', { name: 'Knowledge' }).click();
  await page.getByRole('button', { name: 'Open document library' }).click();
  const docs = page.getByRole('region', { name: 'Document library' });
  await docs.getByRole('button', { name: /Manage documents/ }).click();
  const manager = docs.getByRole('dialog', { name: 'Manage documents' });
  await manager.waitFor();
  await page.screenshot({ path: '../../benchmarks/document-manager.png' });
  const firstRow = manager.locator('.manage-row').first();
  await firstRow.getByRole('button', { name: 'Rename' }).click();
  await docs.getByRole('dialog', { name: 'Rename document' }).getByRole('button', { name: 'Cancel' }).click();
  await firstRow.getByRole('button', { name: 'Remove' }).click();
  await docs.getByRole('dialog', { name: 'Remove document' }).getByRole('button', { name: 'Cancel' }).click();
  await manager.getByRole('button', { name: 'Clear selection' }).click();
  if (await docs.locator('.library-list .file-row').count()) throw Error('Clear selection did not empty library');
  if (await docs.getByRole('button', { name: 'Submit document request' }).isEnabled()) throw Error('Question can run with no selected documents');
  await manager.getByRole('button', { name: 'Select all' }).click();
  if (!await docs.locator('.library-list .file-row').count()) throw Error('Select all did not restore library');
  await manager.getByRole('button', { name: 'Done' }).click();
  const beforeLibrary = await docs.locator('.library-list').boundingBox();
  await docs.getByRole('button', { name: 'Resize document library' }).focus();
  await page.keyboard.press('ArrowRight');
  const afterLibrary = await docs.locator('.library-list').boundingBox();
  if (!beforeLibrary || !afterLibrary || afterLibrary.width <= beforeLibrary.width) throw Error('Document library keyboard resize failed');
  await page.setViewportSize({ width: 1000, height: 800 });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw Error('Documents overflow at web-view width');
  await page.keyboard.press('Control+Alt+4');
  await page.getByRole('region', { name: 'Coding workspace' }).waitFor();
  await page.keyboard.press('Control+Alt+2');
  await page.getByRole('region', { name: 'Document library' }).waitFor();
  if (errors.length) throw Error(errors.join('\n'));
  console.log('Pane resizing, shortcut dialog, and document selection passed');
 } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
