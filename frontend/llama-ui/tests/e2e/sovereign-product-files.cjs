const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const out=path.resolve(process.env.SOVEREIGN_QA_OUTPUT||path.resolve(__dirname,'../../../../outputs/product-verification-20261004'));fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 try{
  const base='http://127.0.0.1:8088';
  const created=await(await page.request.post(base+'/coding/workspaces',{data:{name:'Product browser files '+Date.now()}})).json();
  const id=created.workspace_id;
  await page.request.put(base+'/coding/workspaces/'+id+'/files/notes.txt',{data:{content:'PRODUCT_SEARCH_SENTINEL\n'}});
  await page.goto(base+'/#/');
  await page.getByRole('button',{name:'Code',exact:true}).click();
  const ide=page.getByRole('region',{name:'Coding workspace'});
  await ide.getByLabel('Open coding workspace').selectOption(id);
  const tree=ide.getByLabel('Workspace files');
  const source=tree.getByRole('button',{name:'notes.txt',exact:true});
  await source.click();
  await ide.getByRole('button',{name:'Search files',exact:true}).click();
  await ide.getByRole('textbox',{name:'Search project'}).fill('PRODUCT_SEARCH_SENTINEL');
  await ide.getByText('PRODUCT_SEARCH_SENTINEL',{exact:true}).first().waitFor();
  await ide.getByRole('button',{name:'Show Explorer'}).click();
  await source.click({button:'right'});
  await ide.getByRole('menu',{name:'File actions'}).getByRole('menuitem',{name:/^Copy Ctrl/}).click();
  await source.click({button:'right'});
  await ide.getByRole('menu',{name:'File actions'}).getByRole('menuitem',{name:/^Paste/}).click();
  const copied=tree.getByRole('button',{name:'notes copy.txt',exact:true});
  await copied.waitFor();
  await copied.click({button:'right'});
  await ide.getByRole('menu',{name:'File actions'}).getByRole('menuitem',{name:/^Rename/}).click();
  await ide.getByRole('textbox',{name:'New file name'}).fill('renamed.txt');
  await ide.getByRole('dialog',{name:'Rename file'}).getByRole('button',{name:/^Rename/}).click();
  await tree.getByRole('button',{name:'renamed.txt',exact:true}).waitFor();
  const read=await(await page.request.get(base+'/coding/workspaces/'+id+'/files/renamed.txt')).json();
  if(read.content!=='PRODUCT_SEARCH_SENTINEL\n'||errors.length)throw new Error(JSON.stringify({read,errors}));
  await tree.getByRole('button',{name:'renamed.txt',exact:true}).click();
  await ide.locator('.monaco-editor .view-lines').click();
  await page.keyboard.press('Control+a');await page.keyboard.insertText('PRODUCT_EDIT_VERIFIED\n');
  const saved=page.waitForResponse(r=>r.request().method()==='PUT'&&r.url().endsWith('/files/renamed.txt'));
  await page.keyboard.press('Control+s');if(!(await saved).ok())throw new Error('Editor save failed');
  const edited=await(await page.request.get(base+'/coding/workspaces/'+id+'/files/renamed.txt')).json();
  if(edited.content!=='PRODUCT_EDIT_VERIFIED\n')throw new Error('Editor bytes mismatch');
  await ide.getByRole('button',{name:'New file',exact:true}).click();
  await ide.getByRole('textbox',{name:'New file path'}).fill('created.txt');
  await ide.getByRole('button',{name:'Create file',exact:true}).click();
  await tree.getByRole('button',{name:'created.txt',exact:true}).waitFor();
  fs.writeFileSync(path.join(out,'browser-files.json'),JSON.stringify({workspace_id:id,tree:true,read:true,search:true,copy:true,rename:true,edit:true,create:true,errors},null,2));
  await page.screenshot({path:path.join(out,'browser-files.png')});
  console.log('Browser file tree, read, search, copy and rename passed');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
